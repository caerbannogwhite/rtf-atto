#!/usr/bin/env python3
"""Generate src/codepages.inc, the single-byte code page tables.

Run from the repository root:

    python tools/gen_codepages.py src/codepages.inc

Each table maps the bytes 0x80 to 0xFF of one code page to a Unicode code
point. A byte that the Python codec rejects is written as 0. The file is
written with LF line ends and UTF-8, whatever the platform.
"""
import sys

# Code page number -> Python codec name.
CODE_PAGES = [
    (437, "cp437"),
    (850, "cp850"),
    (852, "cp852"),
    (866, "cp866"),
    (874, "cp874"),
    (1250, "cp1250"),
    (1251, "cp1251"),
    (1252, "cp1252"),
    (1253, "cp1253"),
    (1254, "cp1254"),
    (1255, "cp1255"),
    (1256, "cp1256"),
    (1257, "cp1257"),
    (1258, "cp1258"),
    (10000, "mac_roman"),
]


def decode_table(codec):
    """Return 128 code points for the bytes 0x80 to 0xFF. Undefined bytes give 0."""
    table = []
    for b in range(0x80, 0x100):
        try:
            text = bytes([b]).decode(codec, errors="strict")
        except UnicodeDecodeError:
            table.append(0)
            continue
        if len(text) != 1 or ord(text) > 0xFFFF:
            raise SystemExit("unexpected decode of byte 0x%02X in %s" % (b, codec))
        table.append(ord(text))
    return table


def render():
    lines = [
        "// Generated by tools/gen_codepages.py; do not edit.",
        "// Regenerate with: python tools/gen_codepages.py src/codepages.inc",
        "// Each table holds the Unicode code points of the bytes 0x80 to 0xFF.",
        "// A value of 0 means the byte is undefined in that code page.",
        "",
    ]
    for number, codec in CODE_PAGES:
        table = decode_table(codec)
        assert len(table) == 128
        lines.append("static const std::uint16_t kCp%d[128] = {" % number)
        for i in range(0, 128, 8):
            row = ", ".join("0x%04X" % v for v in table[i:i + 8])
            lines.append("    " + row + ",")
        lines.append("};")
        lines.append("")
    lines.append("static const std::uint16_t* code_page_table(int codePage) {")
    lines.append("  switch (codePage) {")
    for number, _ in CODE_PAGES:
        lines.append("    case %d: return kCp%d;" % (number, number))
    lines.append("    default: return nullptr;")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    if len(argv) != 2:
        sys.stderr.write("usage: python tools/gen_codepages.py <output file>\n")
        return 2
    with open(argv[1], "w", encoding="utf-8", newline="\n") as f:
        f.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
